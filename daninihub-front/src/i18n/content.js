export function detectInitialLanguage() {
  const nav = navigator.language?.toLowerCase() || ''

  if (nav.startsWith('de')) return 'de'
  if (
    nav.startsWith('sr') ||
    nav.startsWith('hr') ||
    nav.startsWith('bs') ||
    nav.startsWith('me')
  ) {
    return 'sr'
  }

  return 'en'
}
